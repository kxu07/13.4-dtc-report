import streamlit as st

st.title("Appendix F: Instructions for Use")

st.write(" 1. Hold your pool cue vertically with the tip facing upwards")

st.write(" 2. Grip the Chalk Pop with your nondominant hand with the chalk facing away from your palm. The recommended grip is fingers on the concave side as shown in Figure __, convex side resting in your palm, but use whatever feels comfortable")
st.image("grip.png", "Figure __: The recommended grip for the Chalk Pop")
st.write(" 3. Rotate the device so the chalk faces downward and position it directly above the cue tip.")
st.write(" 4. Place the center of the chalk onto the cue tip and begin applying small circular wrist motions, gradually increasing the size of the circles as you go. Think of tracing an outward spiral with your wrist.")
