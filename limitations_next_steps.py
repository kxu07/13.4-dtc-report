import streamlit as st
from PIL import Image


st.title("Limitations and Next Steps")

st.write("There are a few areas where the Chalk Pop could be improved. " \
"For one, the chalk itself needing to be semi-spherical limits the market availability of replacements. " \
"Once the chalk wears down, to replace it would require that the user source another semi-spherical piece of chalk." \
" We used a grinder to create a semi-sphere from a cube, but that process is not easily replicable. " \
"To address this, we would want to create a system to make sure the chalk is easily replaceable. " \
"If there was more time for this project, making a easily-replaceable system would be our goal. " \
"We hypothesize that attaching the chalk to a screw, with the screw going into the handle, would allow the user to take the screw out, and likewise the chalk. " \
"This way, the user would be able to swap their chalk and screw system out for a new chalk and screw system. ")
st.write("We would also want to test out different materials for the shroud. " \
"In our design review (see Design Review Summary), we were advised that the flexibility of the shroud could improve the efficacy of our product. " \
"For example, using a more flexible shroud could help the user reach all areas of the chalk. " \
"If we had more time, we definitely want to invest more time into testing a variety of materials.")
